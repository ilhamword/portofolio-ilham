const STORAGE_KEY = 'portfolio_preferred_lang';

export function getCurrentLang() {
  const saved = localStorage.getItem(STORAGE_KEY);
  if (saved && (saved === 'id' || saved === 'en')) {
    return saved;
  }
  // Default to English as standard, or browser preference
  return 'en';
}

export function setLanguage(lang) {
  if (lang !== 'id' && lang !== 'en') return;

  localStorage.setItem(STORAGE_KEY, lang);
  document.documentElement.lang = lang;

  const dict = translations[lang] || translations.en;

  // 1. Translate elements with data-i18n (text content)
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      el.textContent = dict[key];
    }
  });

  // 2. Translate elements with data-i18n-html (HTML content, e.g. <span> or <strong>)
  document.querySelectorAll('[data-i18n-html]').forEach((el) => {
    const key = el.getAttribute('data-i18n-html');
    if (dict[key]) {
      el.innerHTML = dict[key];
    }
  });

  // 3. Update active states on language switcher buttons
  document.querySelectorAll('.lang-btn').forEach((btn) => {
    const btnLang = btn.getAttribute('data-lang');
    if (btnLang === lang) {
      btn.classList.add('lang-btn--active');
      btn.setAttribute('aria-pressed', 'true');
    } else {
      btn.classList.remove('lang-btn--active');
      btn.setAttribute('aria-pressed', 'false');
    }
  });

  // 4. Reinitialize Lucide icons if any were in dynamic content
  if (window.lucide) {
    window.lucide.createIcons();
  }
}

export function initI18n() {
  const initialLang = getCurrentLang();

  // Attach click listeners to language toggle buttons
  document.querySelectorAll('.lang-btn').forEach((btn) => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      const targetLang = btn.getAttribute('data-lang');
      setLanguage(targetLang);
    });
  });

  // Apply the language on startup
  setLanguage(initialLang);
}
